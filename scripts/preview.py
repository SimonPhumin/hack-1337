"""Render preview images (needs harfbuzz's hb-view) and regenerate docs/ligatures.md."""
import subprocess
import tempfile
from pathlib import Path

from check import Shaper, ligature_set
from config import FAMILY, ROOT

COLORS = ["--background=#1e1e1e", "--foreground=#d4d4d4"]
CODE = r"""fn parse(input: &str) -> Result<Vec<Token>, Error> {
    if input.len() >= 2 && input != "<!--" || x == y { return Err(e); }
    let ok = items.iter().filter(|x| x.0 <= 10).count() > 0;
}
const pipe = (f) => (x) => x |> f ?? null; // a := b; c =/= d; e === f
"""


def hb_view(font: Path, text: str, out: Path, size: int = 32, features: str = "") -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as f:
        f.write(text)
    cmd = ["hb-view", f"--font-size={size}", "--margin=32", *COLORS, f"--text-file={f.name}", "-o", str(out), str(font)]
    if features:
        cmd.insert(1, f"--features={features}")
    subprocess.run(cmd, check=True)
    Path(f.name).unlink()


def main() -> None:
    regular = ROOT / "ttf" / f"{FAMILY} Regular.ttf"
    ligs = sorted(ligature_set(Shaper(regular.read_bytes())).values(), key=lambda s: (len(s), s))

    per_row = 16
    rows = [ligs[i:i + per_row] for i in range(0, len(ligs), per_row)]
    hb_view(regular, "\n".join("  ".join(r) for r in rows), ROOT / "preview" / "ligatures.png", size=28)
    hb_view(regular, CODE, ROOT / "preview" / "code.png", size=26)
    hb_view(regular, CODE, ROOT / "preview" / "code-no-ligatures.png", size=26, features="-calt")

    table = ["| Ligature | Characters |", "| --- | --- |"]
    table += [f"| <code>{s.replace('|', '&#124;')}</code> | {' '.join(f'`U+{ord(c):04X}`' for c in s)} |" for s in ligs]
    (ROOT / "docs" / "ligatures.md").write_text(
        "# Ligatures\n\n"
        f"Hack 1337 ships the {len(ligs)} programming ligatures of JetBrains Mono, copied into Hack by "
        "`scripts/ligaturize.py`. They live in the `calt` (contextual alternates) feature.\n\n"
        "This file is generated by `make previews`.\n\n"
        "![Ligatures](../preview/ligatures.png)\n\n"
        "## Stylistic sets\n\n"
        "| Feature | Effect |\n| --- | --- |\n"
        "| `ss01` | Plain comparison operators: no ligatures for `<=` `>=` `==` `!=` "
        "(and sequences built on them, such as `===` `!==` `<=>` `==>`). |\n\n"
        "## All ligatures\n\n" + "\n".join(table) + "\n"
    )
    print(f"rendered previews, {len(ligs)} ligatures")


if __name__ == "__main__":
    main()
